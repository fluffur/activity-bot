package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/BurntSushi/toml"
)

type Message struct {
	Key    string
	Params []string
}

type Translation struct {
	Other string `toml:"other"`
}

var paramRegexp = regexp.MustCompile(`{{\s*\.(\w+)\s*}}`)

func main() {
	messages, err := collectMessages()
	if err != nil {
		panic(err)
	}

	sort.Slice(messages, func(i, j int) bool {
		return messages[i].Key < messages[j].Key
	})

	var out bytes.Buffer

	out.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	out.WriteString("package i18n\n\n")

	out.WriteString("type MessageID string\n\n")

	out.WriteString("const (\n")

	for _, msg := range messages {
		_, _ = fmt.Fprintf(
			&out,
			"\t%s MessageID = %q\n",
			toGoName(msg.Key),
			msg.Key,
		)
	}

	out.WriteString(")\n")

	for _, msg := range messages {
		if len(msg.Params) == 0 {
			continue
		}

		funcName := toGoName(msg.Key) + "Args"

		_, _ = fmt.Fprintf(&out, "\nfunc %s(\n", funcName)

		for _, param := range msg.Params {
			_, _ = fmt.Fprintf(
				&out,
				"\t%s any,\n",
				lowerFirst(param),
			)
		}

		out.WriteString(") map[string]any {\n")
		out.WriteString("\treturn map[string]any{\n")

		for _, param := range msg.Params {
			_, _ = fmt.Fprintf(
				&out,
				"\t\t%q: %s,\n",
				param,
				lowerFirst(param),
			)
		}

		out.WriteString("\t}\n")
		out.WriteString("}\n")
	}

	// #nosec G306
	if err := os.WriteFile("./keys.go", out.Bytes(), 0o644); err != nil {
		panic(err)
	}
}

func collectMessages() ([]Message, error) {
	entries, err := os.ReadDir("locales")
	if err != nil {
		return nil, err
	}

	result := make(map[string][]string)

	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}

		data, err := os.ReadFile(filepath.Join("locales", entry.Name()))
		if err != nil {
			return nil, err
		}

		var messages map[string]Translation

		if err := toml.Unmarshal(data, &messages); err != nil {
			return nil, err
		}

		for key, msg := range messages {
			params := extractParams(msg.Other)

			if existing, ok := result[key]; ok {
				result[key] = mergeParams(existing, params)
			} else {
				result[key] = params
			}
		}
	}

	list := make([]Message, 0, len(result))

	for key, params := range result {
		list = append(list, Message{
			Key:    key,
			Params: params,
		})
	}

	return list, nil
}

func extractParams(text string) []string {
	matches := paramRegexp.FindAllStringSubmatch(text, -1)

	seen := make(map[string]struct{})
	params := make([]string, 0)

	for _, match := range matches {
		name := match[1]

		if _, ok := seen[name]; ok {
			continue
		}

		seen[name] = struct{}{}
		params = append(params, name)
	}

	sort.Strings(params)

	return params
}

func mergeParams(a, b []string) []string {
	seen := make(map[string]struct{})

	for _, v := range a {
		seen[v] = struct{}{}
	}

	for _, v := range b {
		seen[v] = struct{}{}
	}

	result := make([]string, 0, len(seen))

	for v := range seen {
		result = append(result, v)
	}

	sort.Strings(result)

	return result
}

func toGoName(key string) string {
	parts := strings.FieldsFunc(key, func(r rune) bool {
		return r == '_' || r == '-' || r == '.'
	})

	for i := range parts {
		if parts[i] == "" {
			continue
		}

		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}

	return strings.Join(parts, "")
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}

	return strings.ToLower(s[:1]) + s[1:]
}
